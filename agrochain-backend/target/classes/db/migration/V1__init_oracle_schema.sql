-- Oracle schema for AgroChain (users, roles, products, orders, payments, reviews,
-- messages, notifications, wallets, transactions).

CREATE SEQUENCE USERS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE ROLES_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PRODUCTS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE ORDERS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PAYMENTS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE REVIEWS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE MESSAGES_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE NOTIFICATIONS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE ACTIVITY_LOGS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE WALLETS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TRANSACTIONS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE ROLES (
    ID          NUMBER(19) PRIMARY KEY,
    NAME        VARCHAR2(32 CHAR) NOT NULL UNIQUE
);

CREATE TABLE USERS (
    ID          NUMBER(19) PRIMARY KEY,
    EMAIL       VARCHAR2(255 CHAR) NOT NULL UNIQUE,
    PASSWORD    VARCHAR2(255 CHAR) NOT NULL,
    FIRST_NAME  VARCHAR2(120 CHAR) NOT NULL,
    LAST_NAME   VARCHAR2(120 CHAR) NOT NULL,
    PHONE       VARCHAR2(32 CHAR),
    BLOCKED     NUMBER(1) DEFAULT 0 NOT NULL,
    ENABLED     NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT  TIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP NOT NULL
);

CREATE TABLE USER_ROLES (
    USER_ID     NUMBER(19) NOT NULL,
    ROLE_ID     NUMBER(19) NOT NULL,
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_UR_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_UR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID)
);

CREATE TABLE PRODUCTS (
    ID          NUMBER(19) PRIMARY KEY,
    FARMER_ID   NUMBER(19) NOT NULL,
    NAME        VARCHAR2(255 CHAR) NOT NULL,
    PRICE       NUMBER(14,2) NOT NULL,
    QUANTITY    NUMBER(10) NOT NULL,
    CATEGORY    VARCHAR2(120 CHAR) NOT NULL,
    IMAGE_URL   VARCHAR2(1024 CHAR),
    DESCRIPTION VARCHAR2(4000 CHAR),
    ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT  TIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP NOT NULL,
    CONSTRAINT FK_PRODUCTS_FARMER FOREIGN KEY (FARMER_ID) REFERENCES USERS(ID)
);

CREATE TABLE PRODUCT_ORDERS (
    ID                NUMBER(19) PRIMARY KEY,
    BUYER_ID          NUMBER(19) NOT NULL,
    PRODUCT_ID        NUMBER(19) NOT NULL,
    QUANTITY          NUMBER(10) NOT NULL,
    TOTAL_PRICE       NUMBER(14,2) NOT NULL,
    DELIVERY_ADDRESS  VARCHAR2(1000 CHAR) NOT NULL,
    BUYER_DISPLAY_NAME VARCHAR2(255 CHAR),
    STATUS            VARCHAR2(32 CHAR) NOT NULL,
    ORDERED_AT        TIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP NOT NULL,
    CONSTRAINT FK_ORDERS_BUYER FOREIGN KEY (BUYER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_ORDERS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(ID)
);

CREATE TABLE PAYMENTS (
    ID                  NUMBER(19) PRIMARY KEY,
    ORDER_ID            NUMBER(19) UNIQUE NOT NULL,
    METHOD              VARCHAR2(16 CHAR) NOT NULL,
    STATUS              VARCHAR2(16 CHAR) NOT NULL,
    AMOUNT              NUMBER(14,2) NOT NULL,
    EXTERNAL_REFERENCE  VARCHAR2(255 CHAR),
    UPI_TRANSACTION_ID  VARCHAR2(255 CHAR),
    CREATED_AT          TIMESTAMP NOT NULL,
    CONSTRAINT FK_PAYMENTS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES PRODUCT_ORDERS(ID)
);

CREATE TABLE REVIEWS (
    ID          NUMBER(19) PRIMARY KEY,
    BUYER_ID    NUMBER(19) NOT NULL,
    FARMER_ID   NUMBER(19) NOT NULL,
    ORDER_ID    NUMBER(19) UNIQUE,
    RATING      NUMBER(2) NOT NULL,
    COMMENT     VARCHAR2(2000 CHAR),
    CREATED_AT  TIMESTAMP NOT NULL,
    CONSTRAINT FK_REVIEWS_BUYER FOREIGN KEY (BUYER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_REVIEWS_FARMER FOREIGN KEY (FARMER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_REVIEWS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES PRODUCT_ORDERS(ID)
);

CREATE TABLE MESSAGES (
    ID          NUMBER(19) PRIMARY KEY,
    SENDER_ID   NUMBER(19) NOT NULL,
    RECEIVER_ID NUMBER(19) NOT NULL,
    CONTENT     VARCHAR2(4000 CHAR) NOT NULL,
    ORDER_ID    NUMBER(19),
    IS_READ     NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT  TIMESTAMP NOT NULL,
    CONSTRAINT FK_MESSAGES_SENDER FOREIGN KEY (SENDER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_MESSAGES_RECEIVER FOREIGN KEY (RECEIVER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_MESSAGES_ORDER FOREIGN KEY (ORDER_ID) REFERENCES PRODUCT_ORDERS(ID)
);

CREATE TABLE NOTIFICATIONS (
    ID                  NUMBER(19) PRIMARY KEY,
    USER_ID             NUMBER(19) NOT NULL,
    TYPE                VARCHAR2(32 CHAR) NOT NULL,
    TITLE               VARCHAR2(255 CHAR) NOT NULL,
    BODY                VARCHAR2(2000 CHAR) NOT NULL,
    IS_READ             NUMBER(1) DEFAULT 0 NOT NULL,
    RELATED_ENTITY_ID   NUMBER(19),
    CREATED_AT          TIMESTAMP NOT NULL,
    CONSTRAINT FK_NOTIFICATIONS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

CREATE TABLE ACTIVITY_LOGS (
    ID              NUMBER(19) PRIMARY KEY,
    ACTOR_USER_ID   NUMBER(19),
    ACTION          VARCHAR2(120 CHAR) NOT NULL,
    DETAIL          VARCHAR2(4000 CHAR),
    ENTITY_TYPE     VARCHAR2(64 CHAR),
    ENTITY_ID       NUMBER(19),
    CREATED_AT      TIMESTAMP NOT NULL
);

CREATE TABLE WALLETS (
    ID          NUMBER(19) PRIMARY KEY,
    USER_ID     NUMBER(19) NOT NULL UNIQUE,
    BALANCE     NUMBER(14,2) DEFAULT 0 NOT NULL,
    VERSION     NUMBER(19),
    CREATED_AT  TIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP NOT NULL,
    CONSTRAINT FK_WALLETS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

CREATE TABLE TRANSACTIONS (
    ID              NUMBER(19) PRIMARY KEY,
    WALLET_ID       NUMBER(19) NOT NULL,
    TYPE            VARCHAR2(16 CHAR) NOT NULL,
    AMOUNT          NUMBER(14,2) NOT NULL,
    BALANCE_AFTER   NUMBER(14,2) NOT NULL,
    REFERENCE_TYPE  VARCHAR2(64 CHAR),
    REFERENCE_ID    NUMBER(19),
    DESCRIPTION     VARCHAR2(255 CHAR),
    CREATED_AT      TIMESTAMP NOT NULL,
    CONSTRAINT FK_TRANSACTIONS_WALLET FOREIGN KEY (WALLET_ID) REFERENCES WALLETS(ID)
);

